// Session overlay for `dsh <profile> --patch`: trims the per-request prompt for the companion loop.
// - Disables MCP servers other than jingjing (home-level ones such as taptap-maker would add ~17k tokens of tool schemas).
// - Compacts history early: the react loop adds a batch every few seconds, and the default threshold (~80% of a 262k window) comes far too late.
// The overlay is derived from the profile's own composed config on every start, so dsh upgrades and user layers are kept.
// Plain text surgery instead of a YAML round trip: the dump carries `!!js` expressions that must survive verbatim.
import { spawnSync } from 'node:child_process';

export const COMPACTION = { thresholdRatio: 0.25, retainRatio: 0.05 };
const MCP_CLIENT = '@deepseek-ai/dsh-mcp-client';

/** Split a composed-config dump into its top-level rows (each starts with "- " at column 0). */
export function topLevelRows(dump) {
    const rows = [];
    let current = null;
    for (const line of dump.replace(/\r\n?/g, '\n').split('\n')) {
        if (line.startsWith('- ')) {
            current = [line];
            rows.push(current);
        } else if (line.startsWith('#')) {
            current = null;
        } else if (current) {
            // Blank lines belong to the row: block scalars (prompt texts) contain them.
            current.push(line);
        }
    }
    for (const lines of rows) while (lines.length > 1 && lines.at(-1).trim() === '') lines.pop();
    return rows.map(lines => {
        const field = name => lines.map(line => line.match(new RegExp(`^(?:- |  )${name}: (.*)$`))?.[1]).find(Boolean)?.replace(/^'(.*)'$/, '$1');
        return { id: field('id'), name: field('name'), disabled: field('disabled') === 'true', lines };
    });
}

/** Give every nested compaction-basic without its own config the early-compaction policy; null when nothing changes. */
export function withEarlyCompaction(lines, policy = COMPACTION) {
    const out = [];
    let changed = false;
    for (let i = 0; i < lines.length; i++) {
        out.push(lines[i]);
        const match = lines[i].match(/^(\s+)- id: compaction-basic$/);
        if (!match) continue;
        const inner = `${match[1]}  `;
        let end = i + 1;
        while (end < lines.length && lines[end].startsWith(inner)) end++;
        const body = lines.slice(i + 1, end);
        if (body.some(line => line.startsWith(`${inner}config:`) || line.startsWith(`${inner}disabled: true`))) continue;
        out.push(...body, `${inner}config:`, ...Object.entries(policy).map(([key, value]) => `${inner}  ${key}: ${value}`));
        i = end - 1;
        changed = true;
    }
    return changed ? out : null;
}

/** Build the overlay patch text from `dsh <profile> --dump-config` output. */
export function buildOverlay(dump, { keepMcp = false } = {}) {
    const rows = topLevelRows(dump);
    const out = ['# Generated by scripts/start.mjs from the composed profile on every start; do not edit.'];
    const disabledMcp = [];
    if (!keepMcp) {
        for (const row of rows) {
            if (row.name !== MCP_CLIENT || row.id === 'mcp-jingjing' || row.disabled || !row.id) continue;
            out.push(`- id: ${row.id}`, '  disabled: true');
            disabledMcp.push(row.id);
        }
    }
    const presets = [];
    for (const row of rows) {
        if (row.name !== '@deepseek-ai/dsh-agent-preset') continue;
        const lines = withEarlyCompaction(row.lines);
        if (!lines) continue;
        out.push(...lines);
        presets.push(row.id);
    }
    out.push('');
    return { text: out.join('\n'), disabledMcp, presets };
}

/** Run `dsh <profile> --dump-config`; null when dsh is unavailable or fails. */
export function dumpConfig(profile) {
    const result = spawnSync(`dsh ${profile} --dump-config`, { shell: true, encoding: 'utf8', timeout: 60000, windowsHide: true });
    return result.status === 0 && result.stdout.includes('- id: ') ? result.stdout : null;
}
